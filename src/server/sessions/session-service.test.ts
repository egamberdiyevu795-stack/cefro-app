import { beforeEach, describe, expect, it } from "vitest";
import { openDatabase, setDbForTesting } from "@/server/db/client";
import { seedUsers } from "../../../test/db-helpers";
import { createPracticeSession, ownedSessionIds, resolveOwnedSessionId } from "./session-service";

const U = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const V = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";

beforeEach(() => {
  const db = openDatabase(":memory:");
  setDbForTesting(db);
  seedUsers(db, U, V);
});

describe("practice sessions", () => {
  it("are generated by the server, unique, and owned by their creator", () => {
    const a = createPracticeSession(U);
    const b = createPracticeSession(U);
    expect(a).not.toBe(b);
    expect(a).toMatch(/^[0-9a-f-]{36}$/);
    expect(resolveOwnedSessionId(U, a)).toBe(a);
  });

  it("are invisible to other users: a borrowed id resolves to nothing", () => {
    const mine = createPracticeSession(U);
    expect(resolveOwnedSessionId(V, mine)).toBeNull();
    expect(ownedSessionIds(V, [mine]).size).toBe(0);
  });

  it("treat missing, empty and unknown ids as no session", () => {
    expect(resolveOwnedSessionId(U, undefined)).toBeNull();
    expect(resolveOwnedSessionId(U, null)).toBeNull();
    expect(resolveOwnedSessionId(U, "")).toBeNull();
    expect(resolveOwnedSessionId(U, "11111111-1111-4111-8111-111111111111")).toBeNull();
    expect(ownedSessionIds(U, []).size).toBe(0);
  });

  it("can be checked in bulk", () => {
    const a = createPracticeSession(U);
    const b = createPracticeSession(V);
    expect([...ownedSessionIds(U, [a, b, a])]).toEqual([a]);
  });
});
