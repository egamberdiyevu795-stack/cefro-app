import { beforeEach, describe, expect, it } from "vitest";
import { openDatabase, setDbForTesting } from "@/server/db/client";
import { seedUsers } from "../../../test/db-helpers";
import { createPracticeSession, ownedSessionIds, resolveOwnedSessionId } from "./session-service";

const U = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const V = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";

beforeEach(async () => {
  const db = await openDatabase(":memory:");
  setDbForTesting(db);
  await seedUsers(db, U, V);
});

describe("practice sessions", () => {
  it("are generated by the server, unique, and owned by their creator", async () => {
    const a = await createPracticeSession(U);
    const b = await createPracticeSession(U);
    expect(a).not.toBe(b);
    expect(a).toMatch(/^[0-9a-f-]{36}$/);
    expect(await resolveOwnedSessionId(U, a)).toBe(a);
  });

  it("are invisible to other users: a borrowed id resolves to nothing", async () => {
    const mine = await createPracticeSession(U);
    expect(await resolveOwnedSessionId(V, mine)).toBeNull();
    expect((await ownedSessionIds(V, [mine])).size).toBe(0);
  });

  it("treat missing, empty and unknown ids as no session", async () => {
    expect(await resolveOwnedSessionId(U, undefined)).toBeNull();
    expect(await resolveOwnedSessionId(U, null)).toBeNull();
    expect(await resolveOwnedSessionId(U, "")).toBeNull();
    expect(await resolveOwnedSessionId(U, "11111111-1111-4111-8111-111111111111")).toBeNull();
    expect((await ownedSessionIds(U, [])).size).toBe(0);
  });

  it("can be checked in bulk", async () => {
    const a = await createPracticeSession(U);
    const b = await createPracticeSession(V);
    expect([...(await ownedSessionIds(U, [a, b, a]))]).toEqual([a]);
  });
});
