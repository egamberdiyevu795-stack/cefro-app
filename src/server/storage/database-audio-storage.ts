import "server-only";
import { eq } from "drizzle-orm";
import { getDb, type Db } from "@/server/db/client";
import { recordingBlobs } from "@/server/db/schema";
import { AudioNotFoundError, type AudioStorage } from "./audio-storage";

/**
 * Stores recordings in the application database (table `recording_blobs`).
 *
 * Why: serverless function instances share no filesystem, so files cannot hold a recording that one instance
 * uploads and another processes or plays back. The database is the one thing every instance already shares, a
 * recording is about 2 MB, and nothing outside authorised server code can read the table (there is no URL to a
 * recording; /api/speaking/attempts/:id/audio checks ownership and streams the bytes).
 *
 * This is a deliberately simple first implementation behind the AudioStorage interface. Moving recordings to
 * object storage (Vercel Blob, R2, S3) later means adding another implementation and setting
 * AUDIO_STORAGE_PROVIDER; the speaking code, routes and database schema for attempts do not change.
 */
export class DatabaseAudioStorage implements AudioStorage {
  readonly provider = "database";

  /** `db` is injectable for tests; by default the application's shared connection is used on every call. */
  constructor(private readonly db?: Db) {}

  private connection(): Promise<Db> {
    return this.db ? Promise.resolve(this.db) : getDb();
  }

  async save(key: string, data: Buffer, contentType: string): Promise<void> {
    assertValidKey(key);
    const db = await this.connection();
    await db
      .insert(recordingBlobs)
      .values({ storageKey: key, data, contentType, sizeBytes: data.byteLength })
      .onConflictDoUpdate({ target: recordingBlobs.storageKey, set: { data, contentType, sizeBytes: data.byteLength } })
      .run();
  }

  async read(key: string): Promise<Buffer> {
    assertValidKey(key);
    const db = await this.connection();
    const row = await db.select({ data: recordingBlobs.data }).from(recordingBlobs).where(eq(recordingBlobs.storageKey, key)).get();
    if (!row) throw new AudioNotFoundError(key);
    return row.data;
  }

  async delete(key: string): Promise<void> {
    assertValidKey(key);
    const db = await this.connection();
    await db.delete(recordingBlobs).where(eq(recordingBlobs.storageKey, key)).run();
  }
}

/** Same key rule as the local storage: keys are generated by the server, but nothing else is ever accepted. */
function assertValidKey(key: string): void {
  if (!/^[a-zA-Z0-9/_.-]+$/.test(key) || key.includes("..")) throw new Error(`Invalid storage key: ${key}`);
}
