import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

/**
 * Audio for the live validation, produced reproducibly:
 *
 *  - speech: OpenAI text-to-speech reads a KNOWN text (including its mistakes, fillers and repetitions),
 *    which gives an exact reference for checking what the speech-to-text step heard;
 *  - encoding: ffmpeg converts it to the formats the app accepts. The primary one is WebM/Opus, which is what
 *    the browser's MediaRecorder produces (mono, 48 kHz Opus);
 *  - silence and near-silence: generated by ffmpeg.
 *
 * LIMITATION (state it wherever results are reported): this is synthetic speech from a text-to-speech voice. It is
 * clean and consistently paced, with none of a real learner's accent, background noise, microphone or timing.
 * It validates the plumbing and the fidelity of transcription to a known reference, not performance on real
 * learners. Real recordings go through the local-samples harness.
 *
 * Generated files are cached in eval-audio/ (gitignored) so repeated runs do not pay for speech synthesis again.
 */
export type AudioFormat = "webm" | "m4a" | "ogg" | "wav";

export const MIME_BY_FORMAT: Record<AudioFormat, string> = {
  webm: "audio/webm;codecs=opus", // exactly what Chrome's MediaRecorder reports
  m4a: "audio/mp4",
  ogg: "audio/ogg",
  wav: "audio/wav",
};

const CACHE_DIR = path.join(process.cwd(), "eval-audio");

export const TTS_MODEL = process.env.OPENAI_TTS_MODEL || "gpt-4o-mini-tts";
export const TTS_VOICE = process.env.OPENAI_TTS_VOICE || "alloy";
const TTS_INSTRUCTIONS =
  "Read the text exactly as written, word for word, in a moderately slow, natural conversational pace, like a " +
  "non-native learner speaking. Pronounce hesitation words such as um, uh and er as spoken sounds, and say repeated " +
  "words and false starts every time they appear. Do not correct grammar, do not skip or add any words.";

export interface OpenAIUsageLog {
  ttsRequests: number;
  ttsCharacters: number;
  ttsErrors: number;
}
export const ttsLog: OpenAIUsageLog = { ttsRequests: 0, ttsCharacters: 0, ttsErrors: 0 };

function ensureCacheDir() {
  fs.mkdirSync(CACHE_DIR, { recursive: true });
}

function run(command: string, args: string[]): void {
  const result = spawnSync(command, args, { encoding: "utf8" });
  if (result.status !== 0) throw new Error(`${command} failed (exit ${result.status}): ${(result.stderr || "").slice(-400)}`);
}

export function ffmpegAvailable(): boolean {
  return spawnSync("ffmpeg", ["-version"]).status === 0 && spawnSync("ffprobe", ["-version"]).status === 0;
}

/** Duration of an audio file in seconds, as measured by ffprobe (independent of the app). */
export function probeDurationSeconds(file: string): number {
  const result = spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", file], { encoding: "utf8" });
  const value = Number.parseFloat(result.stdout);
  if (!Number.isFinite(value)) throw new Error(`ffprobe could not read the duration of ${file}`);
  return value;
}

const key = (...parts: string[]) => createHash("sha256").update(parts.join("\u0000")).digest("hex").slice(0, 16);

/** Which speech synthesiser produces the reference audio. Independent of the transcription provider under test. */
export function ttsProvider(): "openai" | "gemini" {
  const chosen = process.env.TTS_PROVIDER;
  if (chosen === "openai" || chosen === "gemini") return chosen;
  return process.env.OPENAI_API_KEY ? "openai" : "gemini";
}

const GEMINI_TTS_VOICE = process.env.GEMINI_TTS_VOICE || "Kore";
let geminiTtsModel: string | undefined;

async function discoverGeminiTtsModel(apiKey: string): Promise<string> {
  if (process.env.GEMINI_TTS_MODEL) return process.env.GEMINI_TTS_MODEL;
  if (geminiTtsModel) return geminiTtsModel;
  const response = await fetch("https://generativelanguage.googleapis.com/v1beta/models?pageSize=200", {
    headers: { "x-goog-api-key": apiKey },
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`Gemini model listing failed: HTTP ${response.status}`);
  const body = (await response.json()) as { models?: { name: string; supportedGenerationMethods?: string[] }[] };
  const candidates = (body.models ?? []).map((m) => m.name.replace(/^models\//, "")).filter((n) => /tts/i.test(n));
  if (!candidates.length) throw new Error("No Gemini text-to-speech model is available to this key (set GEMINI_TTS_MODEL).");
  geminiTtsModel = candidates.find((n) => /flash/i.test(n) && !/preview-\d{2}-\d{4}/.test(n)) ?? candidates[0];
  console.log(`[live] Gemini TTS model: ${geminiTtsModel}`);
  return geminiTtsModel;
}

async function synthesizeGeminiWav(text: string, file: string): Promise<void> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new Error("GEMINI_API_KEY is not set");
  const model = await discoverGeminiTtsModel(apiKey);
  ttsLog.ttsRequests += 1;
  ttsLog.ttsCharacters += text.length;
  const prompt = `${TTS_INSTRUCTIONS}\n\nText:\n${text}`;
  const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, {
    method: "POST",
    headers: { "x-goog-api-key": apiKey, "Content-Type": "application/json" },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: { responseModalities: ["AUDIO"], speechConfig: { voiceConfig: { prebuiltVoiceConfig: { voiceName: GEMINI_TTS_VOICE } } } },
    }),
    signal: AbortSignal.timeout(180_000),
  });
  if (!response.ok) {
    ttsLog.ttsErrors += 1;
    throw new Error(`Gemini speech synthesis failed: HTTP ${response.status} ${(await response.text().catch(() => "")).replaceAll(apiKey, "[redacted]").slice(0, 200)}`);
  }
  const body = (await response.json()) as { candidates?: { content?: { parts?: { inlineData?: { mimeType?: string; data?: string } }[] } }[] };
  const part = body.candidates?.[0]?.content?.parts?.find((p) => p.inlineData?.data);
  if (!part?.inlineData?.data) {
    ttsLog.ttsErrors += 1;
    throw new Error("Gemini speech synthesis returned no audio");
  }
  const rate = /rate=(\d+)/.exec(part.inlineData.mimeType ?? "")?.[1] ?? "24000";
  const pcm = path.join(os.tmpdir(), `cefro-${process.pid}-${path.basename(file)}.pcm`);
  fs.writeFileSync(pcm, Buffer.from(part.inlineData.data, "base64"));
  try {
    run("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-f", "s16le", "-ar", rate, "-ac", "1", "-i", pcm, "-ar", "48000", "-c:a", "pcm_s16le", file]);
  } finally {
    fs.rmSync(pcm, { force: true });
  }
}

/** Speech for `text`, as WAV bytes. Calls the configured speech endpoint unless a cached copy exists. */
export async function synthesizeSpeechWav(text: string): Promise<string> {
  ensureCacheDir();
  const provider = ttsProvider();
  const file = path.join(CACHE_DIR, `tts-${key(provider, TTS_MODEL, TTS_VOICE, GEMINI_TTS_VOICE, TTS_INSTRUCTIONS, text)}.wav`);
  if (fs.existsSync(file)) return file;
  if (provider === "gemini") {
    await synthesizeGeminiWav(text, file);
    return file;
  }

  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) throw new Error("OPENAI_API_KEY is not set");
  const baseUrl = process.env.OPENAI_BASE_URL || "https://api.openai.com/v1";
  ttsLog.ttsRequests += 1;
  ttsLog.ttsCharacters += text.length;
  const response = await fetch(`${baseUrl}/audio/speech`, {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({ model: TTS_MODEL, voice: TTS_VOICE, input: text, instructions: TTS_INSTRUCTIONS, response_format: "wav" }),
    signal: AbortSignal.timeout(120_000),
  });
  if (!response.ok) {
    ttsLog.ttsErrors += 1;
    // The error body never contains the key; keep a short excerpt for the report.
    throw new Error(`OpenAI speech synthesis failed: HTTP ${response.status} ${(await response.text().catch(() => "")).slice(0, 200)}`);
  }
  fs.writeFileSync(file, Buffer.from(await response.arrayBuffer()));
  return file;
}

const ENCODERS: Record<AudioFormat, string[]> = {
  // Mono 48 kHz Opus in WebM at a typical MediaRecorder bitrate.
  webm: ["-c:a", "libopus", "-b:a", "32k", "-ac", "1", "-ar", "48000", "-f", "webm"],
  m4a: ["-c:a", "aac", "-b:a", "64k", "-ac", "1", "-ar", "44100", "-f", "mp4"],
  ogg: ["-c:a", "libopus", "-b:a", "32k", "-ac", "1", "-ar", "48000", "-f", "ogg"],
  wav: ["-c:a", "pcm_s16le", "-ac", "1", "-ar", "48000", "-f", "wav"],
};

export function encodeAudio(input: string, format: AudioFormat): string {
  ensureCacheDir();
  const output = path.join(CACHE_DIR, `${path.parse(input).name}.${format}`);
  if (!fs.existsSync(output)) {
    const temp = path.join(os.tmpdir(), `cefro-${process.pid}-${path.basename(output)}`);
    run("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-i", input, ...ENCODERS[format], temp]);
    fs.copyFileSync(temp, output);
    fs.rmSync(temp, { force: true });
  }
  return output;
}

/** Digital silence. */
export function makeSilence(seconds: number, format: AudioFormat = "webm"): string {
  return generated(`silence-${seconds}`, `anullsrc=r=48000:cl=mono`, seconds, format);
}

/** Very quiet broadband noise (roughly -54 dBFS): a microphone left open in a quiet room. */
export function makeNearSilence(seconds: number, format: AudioFormat = "webm"): string {
  return generated(`near-silence-${seconds}`, `anoisesrc=color=white:amplitude=0.002:r=48000`, seconds, format);
}

function generated(name: string, source: string, seconds: number, format: AudioFormat): string {
  ensureCacheDir();
  const wav = path.join(CACHE_DIR, `${name}.wav`);
  if (!fs.existsSync(wav)) {
    run("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", source, "-t", String(seconds), "-ac", "1", "-ar", "48000", "-c:a", "pcm_s16le", wav]);
  }
  return encodeAudio(wav, format);
}

/** Speech for `text` in the requested container, cached. */
export async function speechFile(text: string, format: AudioFormat): Promise<string> {
  return encodeAudio(await synthesizeSpeechWav(text), format);
}
